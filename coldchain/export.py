"""Step 9 export: SQL seed (schema + INSERTs), JSON per table (readings as JSON Lines) from the generated CSVs."""
import json
from pathlib import Path

import pandas as pd

from . import db
from .config import RAW_DIR, DERIVED_DIR, EXPORT_DIR


def _lit(v):
    if v is None or (isinstance(v, float) and pd.isna(v)) or v is pd.NaT:
        return "NULL"
    if isinstance(v, (bool,)):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def export_all(batch=1000):
    EXPORT_DIR.mkdir(parents=True, exist_ok=True)
    schema = (Path(__file__).parent / "schema.sql").read_text()
    sql = open(EXPORT_DIR / "seed_data.sql", "w", encoding="utf-8", newline="\n")
    sql.write("-- Seed data generated by coldchain.generator (seed 20261022). Load into an EMPTY database.\n" + schema + "\n")
    for t in db.TABLE_ORDER:
        src = (RAW_DIR if t in db.INPUT_TABLES else DERIVED_DIR) / f"{t}.csv"
        if not src.exists():
            continue
        n = 0
        jf = open(EXPORT_DIR / (f"{t}.jsonl" if t == "sensor_readings" else f"{t}.json"), "w", encoding="utf-8", newline="\n")
        if t != "sensor_readings":
            jf.write("[")
        first = True
        for chunk in pd.read_csv(src, chunksize=50000):
            cols = ",".join(chunk.columns)
            rows = chunk.astype(object).where(chunk.notna(), None).values.tolist()
            for i in range(0, len(rows), batch):
                sql.write(f"INSERT INTO {t} ({cols}) VALUES\n" + ",\n".join("(" + ",".join(_lit(x) for x in r) + ")" for r in rows[i:i + batch]) + ";\n")
            for rec in chunk.astype(object).where(chunk.notna(), None).to_dict("records"):
                s = json.dumps(rec, default=str)
                jf.write(s + "\n" if t == "sensor_readings" else (("" if first else ",\n") + s))
                first = False
            n += len(chunk)
        if t != "sensor_readings":
            jf.write("]")
        jf.close()
        print(f"  exported {t:30s} {n:>9,d} rows")
    sql.close()
    print("wrote", EXPORT_DIR / "seed_data.sql")
